import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { transform } from 'esbuild';

const SOURCE = 'src/inapp/bridge.js';
const TARGET = 'src/inapp/bridge.generated.ts';

/** bridge.js is copied raw from the backend; the SDK ships it minified. */
export async function minifyBridge(source) {
  const { code } = await transform(source, { minify: true, target: 'es2015', charset: 'utf8' });
  return code.trim();
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const code = await minifyBridge(readFileSync(SOURCE, 'utf8'));
  writeFileSync(
    TARGET,
    `// Generated by scripts/build-bridge.mjs from ${SOURCE}. Do not edit.\nexport const BRIDGE = ${JSON.stringify(code)};\n`,
  );
  console.log(`build-bridge: ${TARGET} is ${code.length} B`);
}
